<script>
const contextTopics = <?php echo json_encode($contextTopics, JSON_HEX_TAG | JSON_HEX_APOS | JSON_HEX_AMP | JSON_HEX_QUOT); ?>;
const topicPills = document.getElementById('topic-pills');
const topicPanel = document.getElementById('topic-panel');

function renderTopicButtons(activeSlug = contextTopics[0].slug) {
    topicPills.innerHTML = '';
    contextTopics.forEach(topic => {
        const btn = document.createElement('button');
        btn.type = 'button';
        btn.className = 'topic-pill' + (topic.slug === activeSlug ? ' active' : '');
        btn.textContent = topic.title;
        btn.addEventListener('click', () => renderTopic(topic.slug));
        topicPills.appendChild(btn);
    });
}

function renderTopic(slug) {
    const topic = contextTopics.find(item => item.slug === slug) || contextTopics[0];
    renderTopicButtons(topic.slug);

    const words = topic.words.map(word => `
        <div class="topic-word-card">
            <div class="topic-word-head">
                <span class="topic-word">${word.word}</span>
                <span class="topic-pos">${word.part_of_speech}</span>
            </div>
            <div class="topic-meaning">${word.meaning}</div>
            <div class="topic-example"><strong>Example:</strong> ${word.example}</div>
        </div>
    `).join('');

    topicPanel.innerHTML = `
        <div class="topic-intro">
            <h4>${topic.title}</h4>
            <p>${topic.description}</p>
        </div>
        <div class="topic-word-grid">
            ${words}
        </div>
    `;
}

renderTopic(contextTopics[0].slug);
</script>

