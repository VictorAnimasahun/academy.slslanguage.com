<h5>Reading for the writer's view</h5>
<p>Opinions are signalled by adjectives (<em>unfortunate, encouraging</em>), reporting verbs (<em>claim, argue, suggest</em>) and modal verbs (<em>may, should</em>). A writer who <em>reports</em> an opinion is not necessarily <em>sharing</em> it.</p>
<h5>Working faster</h5>
<ul><li>Skim the introduction and the conclusion for the writer's position.</li><li>Do not read every word of long examples; read the sentence before and after them.</li><li>Practise on 700-word texts with a timer and lower it by a minute each week.</li></ul>
<div class="lc-take"><strong>Take away.</strong> Know the question type before you read, scan for names and keywords, and separate what a writer reports from what a writer believes.</div></div>
