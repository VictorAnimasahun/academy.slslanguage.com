#!/usr/bin/env python3
"""
Builds IELTS Academic Full Mock 1 (Cambridge IELTS 13 Academic, Test 1) from aca_mock_001_content.py:

    python3 -I database/mocks/build_aca_mock_001.py

writes
    database/migrations/172_ielts_academic_mock_1.sql            (tests, questions, options, answers, catalog, course items)
    resources/mock_tests/aca_full_mock_001_passages.php           (the Reading passages, read by the Reading page)

Checks: 40 Listening and 40 Reading questions numbered 1-40, every question has an answer, every lettered answer is one
of its options. Re-runnable SQL (rows added only where missing), MySQL 5.7-safe, courses found by folder, never by id.
"""
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
spec = importlib.util.spec_from_file_location('content', HERE / 'aca_mock_001_content.py')
C = importlib.util.module_from_spec(spec)
spec.loader.exec_module(C)

MOCK, L, R, W = 'IELTS_ACA_FULL_MOCK_001', 'IELTS_AFM1_L', 'IELTS_AFM1_R', 'IELTS_AFM1_W'
LAUNCHER = 'resources/mock_tests/ielts_aca_full_mock_001.php'
FOLDERS = ['IELTS_Aca_1Mo', 'IELTS_Aca_2Mo', 'IELTS_Aca_3Mo']


def q(s):
    return 'NULL' if s is None else "'" + str(s).replace('\\', '\\\\').replace("'", "''") + "'"


def check(name, rows, answers_at, options_at, type_at):
    nums = [r[1] for r in rows]
    if nums != list(range(1, 41)):
        sys.exit(f'{name}: questions must be numbered 1-40 in order, got {nums}')
    for r in rows:
        ans, opts, qtype = r[answers_at], r[options_at], r[type_at]
        if not ans:
            sys.exit(f'{name} Q{r[1]}: no answer')
        if qtype in ('multiple_choice_single',) and ans[0] not in [o[0] for o in opts]:
            sys.exit(f'{name} Q{r[1]}: answer {ans[0]} not among its options')


def section_sql(out, code, rows, has_stimulus):
    """rows: (part, n, type, stimulus|None, text, instructions, options, answers) for Listening;
             (part, n, type, text, instructions, options, answers) for Reading."""
    out.append(f"\nSET @tid = (SELECT id FROM tests WHERE code = {q(code)} LIMIT 1);")
    shared_opts = None
    for r in rows:
        if has_stimulus:
            part, n, qtype, stim, text, ins, opts, ans = r
        else:
            part, n, qtype, text, ins, opts, ans = r
            stim = None
        out.append(f"INSERT INTO questions (test_id, part_number, question_number, stimulus_text, question_text, question_type, instructions, points, display_order) "
                   f"SELECT @tid, {part}, {n}, {q(stim)}, {q(text)}, {q(qtype)}, {q(ins)}, 1.0, {n * 10} FROM DUAL "
                   f"WHERE @tid IS NOT NULL AND NOT EXISTS (SELECT 1 FROM questions x WHERE x.test_id = @tid AND x.question_number = {n});")
        out.append(f"SET @qid = (SELECT id FROM questions WHERE test_id = @tid AND question_number = {n} LIMIT 1);")
        # A re-run brings an existing question's wording up to date (corrections reach a database that already ran this).
        out.append(f"UPDATE questions SET stimulus_text = {q(stim)}, question_text = {q(text)}, instructions = {q(ins)} WHERE id = @qid;")
        # Listening matching: the box sits on the first question of the group (the page shows it once).
        # Reading matching: every question carries the full list (each has its own dropdown).
        for k, (label, otext) in enumerate(opts, 1):
            correct = 1 if (qtype == 'multiple_choice_single' and label == ans[0]) else 0
            out.append(f"INSERT IGNORE INTO question_options (question_id, option_label, option_text, is_correct, display_order) "
                       f"SELECT @qid, {q(label)}, {q(otext)}, {correct}, {k * 10} FROM DUAL WHERE @qid IS NOT NULL;")
        if qtype != 'multiple_choice_single':
            for i, a in enumerate(ans):
                out.append(f"INSERT INTO question_correct_answers (question_id, answer_text, is_case_sensitive, is_alternative) "
                           f"SELECT @qid, {q(a)}, 0, {1 if i else 0} FROM DUAL WHERE @qid IS NOT NULL "
                           f"AND NOT EXISTS (SELECT 1 FROM question_correct_answers y WHERE y.question_id = @qid AND y.answer_text = {q(a)});")


def main():
    check('Listening', C.LISTENING, 7, 6, 2)
    check('Reading', C.READING, 6, 5, 2)
    if sorted(C.PASSAGES) != [1, 14, 27]:
        sys.exit('Passages must start at questions 1, 14 and 27')

    out = [
        "-- ============================================================",
        "-- Migration 172 -- IELTS Academic Full Mock 1 (Cambridge IELTS 13 Academic, Test 1)",
        "--",
        "-- Generated by database/mocks/build_aca_mock_001.py from aca_mock_001_content.py -- edit those, not this file.",
        "-- Founder, 2026-10-24: IELTS Academic had no mock at all (the four Full Mocks are General Training). Same engine as",
        "-- the Full Mocks: Listening (40Q/30min, audio once, no pause) -> Reading (40Q/60min) -> Writing (2 tasks/60min, AI) ->",
        "-- Speaking (tutor-administered, mock_speaking.php). Answers are the book's official key.",
        "-- Codes: IELTS_ACA_FULL_MOCK_001 (the mock), IELTS_AFM1_L / _R / _W (its sections).",
        "-- Last: Mock Test 1 in Class 8 of the IELTS Academic Crash Course, 2-Month and 3-Month opens it (found by folder).",
        "-- Needs: resources/mock_tests/ielts_aca_full_mock_001.php, aca_full_mock_001_listening/reading.php,",
        "-- aca_full_mock_001_passages.php, includes/mock_test_map.php entry, assets/audio/IELTS_ACA_FULL_MOCK_001/listening_part1-4.mp3,",
        "-- assets/img/mock_tests/IELTS_ACA_FULL_MOCK_001/{listening_map,writing_task1_maps}.png. Re-runnable. MySQL 5.7-safe.",
        "-- ============================================================",
        "",
        "SET NAMES utf8mb4;",
        "",
    ]
    desc = 'Cambridge IELTS 13 Academic, Test 1'
    for code, title, d, cat, mins, n in [
        (MOCK, 'IELTS Academic Mock Test 1', 'Complete IELTS Academic mock exam: Listening (40Q/30min), Reading (40Q/60min), Writing (2 tasks/60min), Speaking (tutor-administered). ' + desc + '.', 'Full', 190, 82),
        (L, 'IELTS Academic Mock 1 — Listening', desc + ' — Listening (40Q/30 min)', 'Listening', 30, 40),
        (R, 'IELTS Academic Mock 1 — Reading', desc + ' — Reading (40Q/60 min)', 'Reading', 60, 40),
        (W, 'IELTS Academic Mock 1 — Writing', desc + ' — Writing (2 tasks/60 min)', 'Writing', 60, 2),
    ]:
        out.append(f"INSERT INTO tests (code, title, description, test_type, category, is_mock_section, duration_minutes, total_questions, is_active) "
                   f"SELECT {q(code)}, {q(title)}, {q(d)}, 'IELTS', {q(cat)}, 1, {mins}, {n}, 1 FROM DUAL "
                   f"WHERE NOT EXISTS (SELECT 1 FROM tests WHERE code = {q(code)});")

    out.append("\n-- ---------- Listening ----------")
    section_sql(out, L, C.LISTENING, True)
    out.append("\n-- ---------- Reading (passages are in resources/mock_tests/aca_full_mock_001_passages.php) ----------")
    section_sql(out, R, C.READING, False)

    out.append("\n-- ---------- Writing (Task 1's instructions hold its image path, as the Writing page expects) ----------")
    out.append(f"SET @tid = (SELECT id FROM tests WHERE code = {q(W)} LIMIT 1);")
    for n, text, img in C.WRITING:
        out.append(f"INSERT INTO questions (test_id, part_number, question_number, question_text, question_type, instructions, points, display_order) "
                   f"SELECT @tid, {n}, {n}, {q(text)}, 'essay', {q(img)}, 1.0, {n * 10} FROM DUAL "
                   f"WHERE @tid IS NOT NULL AND NOT EXISTS (SELECT 1 FROM questions x WHERE x.test_id = @tid AND x.question_number = {n});")

    out += [
        "\n-- ---------- Catalog (mock_exams), as the Full Mocks ----------",
        f"INSERT INTO mock_exams (code, exam_type, title, description, total_duration_minutes, is_active) "
        f"SELECT {q(MOCK)}, 'IELTS', 'IELTS Academic Mock Test 1', "
        f"{q(desc + '. Listening (40Q/30 min), Reading (40Q/60 min), Writing AI-graded (60 min), Speaking tutor-administered.')}, 190, 1 FROM DUAL "
        f"WHERE NOT EXISTS (SELECT 1 FROM mock_exams WHERE code = {q(MOCK)});",
    ]
    for i, (sec, code) in enumerate([('Listening', L), ('Reading', R), ('Writing_Task1', W)], 1):
        out.append(f"INSERT INTO mock_exam_sections (mock_code, section_type, test_code, section_order) SELECT {q(MOCK)}, {q(sec)}, {q(code)}, {i} FROM DUAL "
                   f"WHERE NOT EXISTS (SELECT 1 FROM mock_exam_sections WHERE mock_code = {q(MOCK)} AND section_type = {q(sec)});")

    out += [
        "\n-- ---------- Mock Test 1 (Class 8) of the three IELTS Academic courses opens it ----------",
        "UPDATE lesson_parts p JOIN lessons l ON l.id = p.lesson_id JOIN modules m ON m.id = l.module_id JOIN courses c ON c.id = l.course_id",
        f"   SET p.status = 'ready', p.file_path = {q(LAUNCHER)}, p.test_code = {q(MOCK)}",
        f" WHERE c.folder_name IN ({', '.join(q(f) for f in FOLDERS)}) AND p.kind = 'mock_test'",
        "   AND (m.module_order - 1) * 2 + l.lesson_order = 8;",
        "",
        "-- Check: 40 / 40 / 2 questions; 40 answered Listening, 40 Reading; three Class 8 items ready.",
        "SELECT t.code, COUNT(DISTINCT x.id) AS questions, COUNT(DISTINCT CASE WHEN o.is_correct = 1 OR y.id IS NOT NULL THEN x.id END) AS with_answer",
        "  FROM tests t JOIN questions x ON x.test_id = t.id LEFT JOIN question_options o ON o.question_id = x.id",
        "  LEFT JOIN question_correct_answers y ON y.question_id = x.id",
        f" WHERE t.code IN ({q(L)}, {q(R)}, {q(W)}) GROUP BY t.code;",
        "SELECT c.folder_name, p.title, p.status, p.test_code FROM lesson_parts p JOIN lessons l ON l.id = p.lesson_id",
        "  JOIN modules m ON m.id = l.module_id JOIN courses c ON c.id = l.course_id",
        f" WHERE c.folder_name IN ({', '.join(q(f) for f in FOLDERS)}) AND p.kind = 'mock_test' AND (m.module_order - 1) * 2 + l.lesson_order = 8;",
        "",
    ]
    (ROOT / 'database/migrations/172_ielts_academic_mock_1.sql').write_text('\n'.join(out), encoding='utf-8')

    php = ["<?php",
           "// Reading passages of IELTS Academic Mock 1 (Cambridge IELTS 13 Academic, Test 1), keyed by the first question",
           "// of each passage. Generated by database/mocks/build_aca_mock_001.py -- edit aca_mock_001_content.py, not this file.",
           "return ["]
    for k in sorted(C.PASSAGES):
        body = C.PASSAGES[k].replace('\\', '\\\\').replace("'", "\\'")
        php.append(f"    {k} => '{body}',")
    php.append("];\n")
    (ROOT / 'resources/mock_tests/aca_full_mock_001_passages.php').write_text('\n'.join(php), encoding='utf-8')
    print(f'Listening {len(C.LISTENING)}, Reading {len(C.READING)}, Writing {len(C.WRITING)}, passages {len(C.PASSAGES)}', file=sys.stderr)


main()
